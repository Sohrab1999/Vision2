let active = false;
const subs = new Set<() => void>();

/** نوشتنِ پرچم — همگام، و خبردادنِ مشترکین فقط در تغییرِ واقعی (idempotent). */
export function setListenSurface(on: boolean): void {
  if (on === active) return;
  active = on;
  for (const cb of subs) cb();
}

/** اشتراکِ useSyncExternalStore — خروجیِ تابع، تابعِ لغوِ اشتراک است. */
export function subscribeListenSurface(cb: () => void): () => void {
  subs.add(cb);
  return () => {
    subs.delete(cb);
  };
}

/** snapshotِ کلاینت — همیشه boolean (هویتِ پایدار برای useSyncExternalStore). */
export function listenSurfaceSnapshot(): boolean {
  return active;
}

/** snapshotِ سرور — سطحِ شنیدار رویِ سرور معنا ندارد؛ همیشه خاموش. */
export function listenSurfaceServerSnapshot(): boolean {
  return false;
}
