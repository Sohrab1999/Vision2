// چرا؟ تعارضِ دومِ کلیدِ T (درسِ r409): کلیدِ T سراسری «شب/روز» است؛
// سطح‌هایِ شنیدارِ تمرکزمحور (فلش‌کارت، جدولِ افعالِ ضمیمه) همان T را
// «روخوانیِ هدف/دوبارهشنیدن» میکنند. حکمِ r409 پابرجا: تعارضِ کلیدِ
// مشترک با پرچمِ مالکیتِ فاز حل میشود نه با تغییرِ کلید.
//
// قرارداد (جراحی — فراتر از T نیست):
//  · پرچم فقط «T» را از پوسته میگیرد — حروفِ ناوبری (H/D/E/...) و
//    ارقامِ تبِ درس پابرجایند؛ سطحِ شنیدار ناوبر نیست، شنیدار است.
//  · فلش‌کارت: تا نما باز است T مالِ آن است (چیپِ رویِ کارت همیشه
//    هدفِ معتبر دارد).
//  · جدولِ افعال: فقط وقتی «آخرین شنیده»ای هست پرچم روشن است —
//    بی‌شنیده، T همان شب/روز میماند (صداقتِ r236: بی‌هدف، هیچ).
//  · پرچم فقط حافظهٔ همین تب است — هیچ نوشتنی به استورِ یادگیری و
//    هیچ persistای. مالکانِ نوشتن: Flashcards و IrregularVerbsTable؛
//    مالکِ خواندن: راهنمای سراسری (شاخهٔ KeyT).
