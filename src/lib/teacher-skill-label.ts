import { COVERAGE_SKILLS } from "@/lib/coverage-map";

const TEACHER_CATEGORY_EXTRA: Record<string, string> = {
  rush: "چالش برق‌آسا",
  "spell-rush": "دیکتهٔ برق‌آسا",
  exam: "آزمون جامع",
  final: "پایان ترم",
  mistakes: "مرور اشتباهات",
  synant: "مترادف و متضاد",
  duel: "نبرد دو‌نفره",
  "my-words-dictation": "دیکتهٔ واژه‌های من",
  "srs-due-dictation": "دیکتهٔ مرور هوشمند",
  "exam-dictation": "دیکتهٔ آزمون جامع",
};

export function teacherSkillLabel(key: string): string {
  return COVERAGE_SKILLS.find((s) => s.key === key)?.label ?? TEACHER_CATEGORY_EXTRA[key] ?? key;
}
