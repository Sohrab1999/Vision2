// تا حالا هر جا فهرستِ درها لازم می‌شد، دستی نوشته می‌شد — کارتِ راهنمای
// r242 پنج ردیف را هاردکد داشت. از این راند کارتِ راهنما (و هر مصرف‌کنندهٔ
// آینده) از همین داده رندر می‌شود: درِ نو به فهرست اضافه می‌شود، کارت خودش
// تازه می‌شود — «فهرستِ زنده».
//
// قراردادِ هر در:
//   • lead — برچسبِ زمردیِ محل با «:» (ردیفِ فرمان‌یاب lead ندارد؛ محلش
//     داخلِ خودِ متن است — همان شکلِ r242 که گاردِ متنی دارد).
//   • keys — فقط کلیدِ واقعی؛ چهار درِ کلیک‌محور هیچ کلیدِ جعلی ندارند
//     (قراردادِ صداقتِ r242).
//   • action — کنشِ «باز کردنِ همان در» (بندِ ② پیشنهادِ ۲۴۲) که
//     shortcut-guide تفسیرش می‌کند.
//   • closedHint — توضیحِ صادقانه برایِ وقتی که در هنوز وجود ندارد
//     (هدر بی‌رکورد: «با نخستین دیدنِ ضمیمه باز می‌شود»).
// ------------------------------------------------------------------

export type ResumeDoorAction =
  | { kind: "open-palette" }
  | { kind: "focus-header" }
  | { kind: "goto-home" }
  | { kind: "goto-appendix" }
  | { kind: "open-profile" };

export type ResumeDoorId = "palette" | "header" | "home" | "appendix" | "profile";

export interface ResumeLoopDoor {
  id: ResumeDoorId;
  lead: string | null;
  text: string;
  keys?: string[];
  openLabel: string;
  closedHint?: string;
  action: ResumeDoorAction;
}

// ------------------------------------------------------------------
// راند ۲۴۴ — دومین مصرفِ «فهرستِ زنده»: گروهِ «درهای حلقه» در فرمان‌یاب
// (بندِ ① پیشنهادِ ۲۴۳). فرمان‌های پالت از همین داده ساخته می‌شوند —
// درِ نو = یک فرمانِ تازه در پالت، بدونِ ردیفِ دستی.
//
// شناسهٔ فرمانِ هر در: «door-<id>» — ثابت و خودکفا (سبکِ قراردادهایِ
// شناسهٔ r241: اجرا با خودِ شناسه داوری می‌شود نه ایندکسِ رندر).
// ------------------------------------------------------------------

export const DOOR_CMD_PREFIX = "door-";
export const doorCmdId = (id: ResumeDoorId): string => `${DOOR_CMD_PREFIX}${id}`;

// راند ۲۴۵ — نامِ کوتاهِ هر در برایِ ردیف‌هایِ فشرده (پروفایل/پالت):
// درِ leadدار = leadِ بدونِ «:» (هدر/خانه/ضمیمه/پروفایل)؛ درِ بی‌lead
// (فرمان‌یاب) = نخستینِ بخشِ متنش پیش از «—». یک اشتقاق، یک منبع —
// مصرف‌کننده‌هایِ ردیفِ فشرده هرگز نامِ در را دوباره نمی‌نویسند.
export function doorShortName(door: ResumeLoopDoor): string {
  if (door.lead) return door.lead.replace(/:\s*$/, "");
  return door.text.split("—")[0]!.trim();
}

// رویدادِ پالسِ درِ هدر (بندِ ② پیشنهادِ ۲۴۳): دکمهٔ هدر خودش مالکِ
// پالسِ زرشکیِ گذراست — پرنده‌هایِ در (راهنما/فرمان‌یاب) فقط رویداد را
// می‌فرستند؛ منطقِ نمایش در یک نقطه است.
export const PULSE_HEADER_RESUME_EVENT = "pulse-header-resume";

// تحویلِ فوکوس بینِ دو دایالوگِ رادیکس (درسِ بزرگِ r243): دایالوگِ بسته‌شونده
// بعد از انیمیشنِ خروجِ ۲۰۰ms فوکوس را به فراخوانش برمی‌گرداند؛ کنشِ
// فوکوس‌برِ در (باز کردنِ فرمان‌یاب/پروفایل، فوکوسِ هدر) بعد از این دوره
// اجرا می‌شود — راهنما و فرمان‌یاب هر دو همین قرارداد را دارند.
export const DOOR_HANDOFF_DELAY_MS = 260;

/**
 * باز کردنِ درِ هدر: اسکرولِ نرم به دکمهٔ واقعی + فوکوس + رویدادِ پالس.
 * دکمه هست نیست (بی‌رکورد یا رویِ خودِ ضمیمه) = هیچ — صداقتِ r236.
 * true = دکمه پیدا شد و در باز شد.
 */
export function focusHeaderDoor(): boolean {
  if (typeof document === "undefined") return false;
  const btn = document.querySelector<HTMLElement>('[data-testid="header-resume-button"]');
  if (!btn) return false;
  btn.scrollIntoView({ block: "center", behavior: "smooth" });
  btn.focus();
  window.dispatchEvent(new CustomEvent(PULSE_HEADER_RESUME_EVENT));
  return true;
}

