// تایمرِ سؤال است و عددی که در duel:state می‌فرستد ملاکِ نمایشِ لابی.
//
// خالص و بدونِ هیچ وابستگی — هم سرویسِ ۳۰۰۳ (گِرِفتِ ورودیِ سیم) و هم
// لابی/کارنامه (برچسب‌ها) همین قرارداد را مصرف می‌کنند تا سه سرِ سیم
// همیشه یک عدد ببینند.
// ------------------------------------------------------------------

export interface DuelPace {
  ms: number;
  key: "fast" | "normal" | "slow";
  label: string;
}

/** سه ریتمِ بسته‌بندی‌شدهٔ لابی — کلاینت فقط همین‌ها را پیشنهاد می‌دهد */
export const DUEL_PACES: readonly DuelPace[] = Object.freeze([
  { ms: 8_000, key: "fast", label: "سریع" },
  { ms: 15_000, key: "normal", label: "معمول" },
  { ms: 25_000, key: "slow", label: "آرام" },
]);

/** ریتمِ پیش‌فرض — هم لابیِ تازه و هم ورودیِ خرابِ سیم به همین‌جا می‌رسد */
export const DEFAULT_PACE_MS = 15_000;

/**
 * سگ‌منتِ ضد قفل‌شدن، بالایِ ریتمِ خودِ اتاق: کلاینتِ قفل‌شده پس از
 * paceMs + این مهلت، سؤالش را سرور خودش جلو می‌برد (غلط) — همان
 * STALL_GRACE_MSِ قدیم، فقط به‌جای ثابتِ سراسری، بر پایهٔ ریتمِ اتاق.
 */
export const STALL_EXTRA_MS = 4_000;

// r385 — faDigits عمداً اینجاست: داورِ ۳۰۰۳ همین فایل را بیواسطه مصرف
// میکند («خالص و بدونِ هیچ وابستگی» — قراردادِ هدر) و مالکِ دامنهٔ
// lib/time-fa برای همین سیمِ سه‌سرویسی به این فایل واردات ندارد.
// دو «نام» برای ایدئومِ ارقام (faNum/faDigits) در سرشماریِ r385 ثبت شد —
// استثنایِ مستند، نه رت؛ گریپهایِ آینده این حاشیه را میبینند.
const faDigits = (v: number | string): string =>
  String(v).replace(/\d/g, (d) => "۰۱۲۳۴۵۶۷۸۹"[Number(d)]);

/**
 * ورودیِ نامعلومِ سیم → یکی از سه ریتمِ مجاز.
 *  • عضوِ دقیقِ فهرست → همان
 *  • عددِ سالمِ داخلِ گسترهٔ ریتم‌ها [۸هزار..۲۵هزار] → نزدیک‌ترین ریتم؛
 *    گرهِ دوسر (فاصلهٔ برابر) → آرام‌تر (عددِ بزرگ‌تر): ابهامِ گِرِفت
 *    هرگز وقتِ بازیکن را کم نکند
 *  • عددِ بیرونِ گستره (صفر/منفی/خیلی‌بزرگ — دست‌ساز است نه انتخاب) →
 *    پیش‌فرض؛ نه اینکه به سریع‌ترین ریتم بچسبد و وقتِ حریف را بقاپد
 *  • هر چیزِ دیگر (ناني/بی‌نهایت/رشته/شیء) → پیش‌فرض — بدونِ throw
 */
export function clampPaceMs(raw: unknown): number {
  if (typeof raw !== "number" || !Number.isFinite(raw)) return DEFAULT_PACE_MS;
  const exact = DUEL_PACES.find((p) => p.ms === raw);
  if (exact) return exact.ms;
  const min = DUEL_PACES[0].ms;
  const max = DUEL_PACES[DUEL_PACES.length - 1].ms;
  if (raw < min || raw > max) return DEFAULT_PACE_MS;
  let best = DUEL_PACES[0];
  for (const p of DUEL_PACES) {
    // <= در پیمایشِ صعودی یعنی گرهِ دوسر به عنصرِ بعدی (آرام‌تر) می‌رسد
    if (Math.abs(p.ms - raw) <= Math.abs(best.ms - raw)) best = p;
  }
  return best.ms;
}

/** برچسبِ فارسیِ ریتم — «۸ ثانیه» با ارقامِ فارسی؛ ورودیِ خراب → پیش‌فرض */
export function paceSecondsLabel(ms: unknown): string {
  const pace = clampPaceMs(ms);
  return `${faDigits(pace / 1000)} ثانیه`;
}
