/** Apply the phased translations onto the exam bank at load time. */
export function applyExamTranslations(bank: QuizQuestion[]): void {
  for (const q of bank) {
    const fa = EXAM_FA[q.id];
    if (fa && !q.translation) q.translation = fa;
  }
}
