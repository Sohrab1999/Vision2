// امتیازدهی سرعت «نبرد دودنفره» — مرجع-سرور (SEC، ممیزی 2026-10-12).
// پیش‌تر پاداش سرعت از msِ «گزارشیِ کلاینت» محاسبه می‌شد؛ کلاینتی که
// پیام را دستکاری می‌کرد با ms:0 همیشه سقف پاداش می‌گرفت و جدول نبرد
// می‌شکست. اکنون ساعت هر سؤال روی خودِ سرور تیک می‌خورد: از لحظهٔ
// پردازش پاسخ قبلی (یا شروع مسابقه) تا رسیدن این پاسخ. کلاینت در این
// بازه یک نمایش بازخورد ۴۸۰ms و یک رفت‌وبرگشت شبکه دارد → با کسری
// ثابت جبران می‌شود تا امتیاز بازیکن صادقانه عملاً همان قبلی بماند؛
// هیچ ورودی کلاینت دیگر در امتیاز اثر ندارد.
// ------------------------------------------------------------------

export const BASE_POINTS = 100;
/** هر ۱۵۰ms تأخیر، یک امتیاز از پاداش کم می‌شود */
export const BONUS_STEP_MS = 150;
/** نمایش بازخوردِ «درست» در کلاینت پیش از رفتن به سؤال بعدی */
export const FEEDBACK_WINDOW_MS = 480;
/** پوشش رفت‌وبرگشت شبکه + زمان رندر کلاینت */
export const RTT_TOLERANCE_MS = 250;

/** پاداش سرعت ۰..۱۰۰ — صرفاً از زمان‌سنجی خودِ سرور (فقط برای پاسخ درست صدا زده می‌شود) */
export function speedBonus(serverElapsedMs: number): number {
  const estimate = Math.max(0, Math.floor(serverElapsedMs) - FEEDBACK_WINDOW_MS - RTT_TOLERANCE_MS);
  return Math.max(0, BASE_POINTS - Math.floor(estimate / BONUS_STEP_MS));
}
