#!/usr/bin/env node
/**
 * build-booklet-data.cjs — مبدلِ JSON استخراج‌شده به ماژول‌های TS دادهٔ جزوه (راند ۲۰۹)
 *
 * ورودی: /tmp/booklets/grade{7,8,9}.json  (خروجیِ scripts/extract-booklets.py)
 * خروجی: src/data/booklet/grade{7,8,9}.ts
 *
 * پاک‌سازی‌های نهایی همین‌جا انجام می‌شود:
 * - حذفِ هر بقایای نامِ مؤلف/ناشر/تماس (گاردِ نهایی پیش از ورود به باندل)
 * - فشردنِ فاصله‌ها و نقطه‌چین‌های طولانی
 * - محدود کردن طول رشته‌ها (گارد در برابر خطاهای تجزیه)
 */
const fs = require("fs");
const path = require("path");

const SRC = "/tmp/booklets";
const DEST = path.join(__dirname, "..", "src", "data", "booklet");

// الگوهای ممنوع — گاردِ نهایی (هم‌قراردادِ extract-booklets.py)
const FORBIDDEN = [
  /لطفی/i, /بوکان/i, /lotfi/i, /موبایل/, /تلگرام/, /اینستا/,
  /0?0914\d{7,}/, /جمال\s*احمدی/i, /تألیف\s*و\s*گردآور/,
];

function cleanStr(s, max = 400) {
  if (typeof s !== "string") return "";
  let t = s.replace(/\s+/g, " ").replace(/\.{4,}/g, "……").replace(/\u2026{2,}/g, "……").trim();
  if (t.length > max) t = t.slice(0, max).trim();
  return t;
}

function isClean(s) {
  return !FORBIDDEN.some((re) => re.test(s));
}

function cleanLines(lines) {
  const out = [];
  for (const l of lines || []) {
    const en = cleanStr(l.en || "", 300);
    const fa = cleanStr(l.fa || "", 300);
    if (!en && !fa) continue;
    if (!isClean(en) || !isClean(fa)) continue;
    out.push({ speaker: l.speaker ? cleanStr(l.speaker, 40) : null, en, fa });
  }
  return out;
}

function buildGrade(g) {
  const data = JSON.parse(fs.readFileSync(path.join(SRC, `grade${g}.json`), "utf8"));
  const lessons = {};
  for (const [num, slot] of Object.entries(data.lessons || {})) {
    const secs = [];
    if (slot.vocab && slot.vocab.length) {
      const rows = slot.vocab
        .map((p) => ({ en: cleanStr(p.en, 120), fa: cleanStr(p.fa, 160) }))
        .filter((p) => p.en && p.fa && isClean(p.en + p.fa));
      if (rows.length) secs.push({ kind: "vocab", title: "واژگان جزوه", rows });
    }
    if (slot.dialogue && slot.dialogue.lines && slot.dialogue.lines.length) {
      const lines = cleanLines(slot.dialogue.lines);
      if (lines.length) secs.push({ kind: "dialogue", title: "مکالمهٔ کتاب درسی", lines });
    }
    for (const pr of slot.practice || []) {
      const lines = cleanLines(pr.lines);
      if (lines.length) secs.push({ kind: "practice", title: cleanStr(pr.title, 160) || "تمرین‌ها", lines });
    }
    if (slot.notes && slot.notes.length) {
      const paras = slot.notes
        .map((p) => cleanStr(p, 500))
        .filter((p) => p.length >= 8 && isClean(p));
      if (paras.length) secs.push({ kind: "notes", title: "درسنامه و نکات", paras });
    }
    if (slot.exam && slot.exam.length) {
      const items = slot.exam.map((p) => cleanStr(p, 400)).filter((p) => p.length >= 4 && isClean(p));
      if (items.length) secs.push({ kind: "exam", title: "نمونه سؤالات امتحانی", items });
    }
    if (secs.length) lessons[Number(num)] = secs;
  }
  // فعل‌های بی‌قاعده در سطح پایه — به درسِ ۱ (یا بخشِ عمومی) می‌چسبند
  if (data.general && data.general.verbs && data.general.verbs.length) {
    const rows = data.general.verbs
      .map((v) => ({
        forms: (v.forms || []).slice(0, 4).map((f) => cleanStr(f, 60)),
        fa: cleanStr(v.fa, 120),
      }))
      .filter((v) => v.forms.length >= 2 && v.fa && isClean(v.fa + v.forms.join(" ")));
    if (rows.length) {
      const target = Number(Object.keys(lessons)[0] || 1);
      lessons[target] = lessons[target] || [];
      lessons[target].push({ kind: "verbs", title: "افعال بی‌قاعده", rows });
    }
  }
  return lessons;
}

function emit(g, lessons) {
  const body = JSON.stringify(lessons);
  const head = `// AUTO-GENERATED by scripts/build-booklet-data.cjs — DO NOT EDIT BY HAND
// منبع: جزوهٔ پایهٔ ${g === 7 ? "هفتم" : g === 8 ? "هشتم" : "نهم"} (راند ۲۰۹) — بدونِ نامِ مؤلف/ناشر طبق درخواستِ مالک
import type { BookletGradeData } from "@/lib/booklet-types";

export const grade${g}Booklet: BookletGradeData = ${body};
`;
  fs.writeFileSync(path.join(DEST, `grade${g}.ts`), head, "utf8");
  const secs = Object.values(lessons).reduce((n, s) => n + s.length, 0);
  console.log(`grade${g}.ts: ${Object.keys(lessons).length} lessons, ${secs} sections, ${(head.length / 1024).toFixed(0)} KB`);
}

const grades = process.argv.slice(2).map(Number);
for (const g of grades.length ? grades : [7, 8, 9]) {
  emit(g, buildGrade(g));
}
