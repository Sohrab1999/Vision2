//
// قراردادِ هر در (هم‌خانوادهٔ ResumeDoorCoverageEntry):
//   • label — نامِ کوتاهِ در؛ leadِ زمردیِ ردیفِ راهنما.
//   • text — «خانه چه چیزی به یاد دارد» با زبانِ یادگیرنده.
//   • gateHint — گیتِ صادقِ ساختِ در؛ هر ردیف زیرِ خودش «چه‌وقت هست»
//     را می‌گوید (قراردادِ صداقتِ r236: بی‌رکورد هیچ).
//   • file — مسیرِ مصرف‌کننده نسبت به src/components/study — گاردِ
//     «داده ↔ درخت» در tests/return-cluster-guide-r367.test.tsx با
//     probe تطبیقش می‌دهد: probe در فایلِ ثبتشده هست و در هیچ فایلِ
//     دیگری از درخت نیست (کپیِ ناآگاهانه و جابه‌جایی هر دو می‌شکنند).
//   • action همهٔ درها یکی است: رفتن به خانه — درها فقط آن‌جا زندگی
//     می‌کنند (همان شاخهٔ goto-homeِ runDoorAction؛ یک منطق، یک نقطه).
// ------------------------------------------------------------------

