/**
 * Pure domain — percent helpers (audit §10 R-4 + r388 twin-audit census).
 *
 * «بخشی از کل» به‌صورت عدد صحیح ۰ تا ۱۰۰. تا گام ۶ این محاسبه در ۱۲ نقطهٔ
 * پراکنده تکرار شده بود با رفتار ناسازگار در حالت صفر (بعضی‌ها گارد داشتند،
 * بعضی‌ها نه) و بعضی جاها سقف ۱۰۰ دستی. اکنون یک قرارداد:
 * مخرج نامعتبر یا صفر → ۰؛ خروجی همیشه در بازهٔ ۰ تا ۱۰۰ محدود می‌شود.
 *
 * r388 — سرشماریِ «درصدِ فارسی» (الگویِ ممیزیِ دوقلوی r382..r387): قالبِ
 * «٪» در ~۹۹ سایتِ ۵۴ فایل و تبدیلِ ×۱۰۰ در ۲۷ سایت تکرار میشود. حکم:
 *  • «بخش از کل» از همان §۱۰ مالکِ همین‌جاست (percent) — سالم، ۲۰+ مصرفکننده.
 *  • تنها زیرگروهِ بایتهمسان با یک قرارداد: قدمِ «نرخِ ۰..۱ → درصدِ نمایشی»
 *    (Math.round(rate*100)) که در ۳ سایتِ نما بایتبهبایت تکرار شده بود و
 *    هیچ گاردی نداشت (نرخِ NaN بیصدا «NaN٪» رندر میکرد — همان کلاسِ
 *    باگِ «NaN ماه پیش» r385) و سقفِ >۱ را نمیشکست. اکنون percentFromRate.
 *  • گویشهایِ عمدی که نباید یکجا شوند (سندِ حکم — گریپِ آینده حکم میبیند نه سهو):
 *    pctFaِ اعشاریِ dictionary-view (ممیزِ فارسی ٫)؛ قدمِ clampِ پیشرفتِ
 *    badges؛ بومِ share-image (dialectِ مستندِ r288 — پارامترِ total از
 *    بیرون میآید)؛ میدانهایِ rate با صفرِ دامنهای خودشان (word-risk:
 *    ندیده → ۱؛ weekly-digest: correct=0 → ۰)؛ درصدِ CSSِ نوارها (سبک،
 *    نه متن)؛ «%» لاتینِ lesson2 (محتوایِ آموزشیِ انگلیسی).
 *    قالبِ متنِ «faNum(x)٪» در بقیهٔ ~۹۵ سایت گویشِ دامنهای است (سابقهٔ
 *    P8-مسیرِ B: مستند شود، سوییپِ مکانیکیِ بیاثر نشود) — percentFa در
 *    مالکِ قالبِ فارسی (time-fa) زندگی میکند و فقط قراردادهایِ واقعاً
 *    مشترک قرض میگیرند.
 */
export function percent(part: number, whole: number): number {
  if (!Number.isFinite(part) || !Number.isFinite(whole) || whole <= 0) return 0;
  return Math.min(100, Math.max(0, Math.round((part / whole) * 100)));
}

/**
 * r388 — نرخِ ۰..۱ → درصدِ صحیحِ نمایشی ۰..۱۰۰.
 * قرارداد: ورودیِ نامتناهی/NaN → ۰ (بدونِ «NaN٪»؛ تماسدهنده گویشِ صفرِ
 * دامنهاش را خودش پیش از این انتخاب کرده — اینجا فقط نمایشِ امن)؛ خروجی
 * با Math.round گرد و در ۰..۱۰۰ محدود میشود (نرخِ >۱ به ۱۰۰ میچسبد).
 * خالص و بیواردات — رویِ سیمِ سهسرویسی هم امن است.
 */
export function percentFromRate(rate: number): number {
  if (!Number.isFinite(rate)) return 0;
  return Math.min(100, Math.max(0, Math.round(rate * 100)));
}
