// ------------------------------------------------------------------
// r355 — «تنِ بودجه» — تکحقیقتِ ریاضیِ آستانههایِ بودجه.
//
// دو ردیفِ تنظیمات (r347 روخوانی، r348 توضیحِ هوشمند) آستانهها را
// درونخطی تکرار میکردند (>=85 نزدیک، >=60 گرم)؛ r355 همین ریاضی را
// به یک موتورِ خالص میآورد تا نبض (سومین مصرفکننده) هم بدونِ رونویسی
// بخواند — قفلِ ساختاری «آستانه فقط اینجاست» اجازهٔ نسخهٔ موازی
// نمیدهد (درسِ BOMِ خانوادهٔ CSV: تکحقیقت قرض داده میشود، ساخته نمی‌شود).
//
// قراردادِ صادقانه: ورودیِ ناممکن (cap<=0، NaN، منفی) هرگز تنِ
// دروغین نمیسازد — به «صفرِ آرام» برمیگردد؛ دیدبانی، نه درستکاری.
// ------------------------------------------------------------------

export type BudgetTone = "calm" | "warm" | "near";

/** درصدِ مصرفِ بودجه — بسته در [0,100]؛ ورودیِ نامعتبر ⇒ ۰ */
export function budgetPercent(used: number, cap: number): number {
  if (!Number.isFinite(used) || !Number.isFinite(cap) || cap <= 0) return 0;
  const pct = Math.round((used / cap) * 100);
  if (!(pct > 0)) return 0; // -0 و ۰ و منفی همگی ⇒ صفرِ مثبتِ صادق
  return Math.min(100, pct);
}

/** تنِ بودجه — آستانههایِ واحدِ ردیفهایِ تنظیمات: گرم ≥۶۰، نزدیک ≥۸۵ */
export function budgetTone(pct: number): BudgetTone {
  if (pct >= 85) return "near";
  if (pct >= 60) return "warm";
  return "calm";
}
