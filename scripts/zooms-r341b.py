import fitz

doc = fitz.open("/home/z/my-project/upload/جزوه جامع دهم .pdf")

STRIPS = [
    # (pno0, y0, y1, name)
    (278, 130, 146, "r341-tr-q1"),    # حایل/حال
    (278, 228, 244, "r341-tr-q3"),    # ماشیر ن / مین نل
    (278, 270, 287, "r341-tr-q4"),    # یگ / قدییم / ا م
    (278, 311, 327, "r341-tr-q5"),    # شکالت / میر فت
    (278, 394, 411, "r341-tr-q7"),    # مایه / سیایه
    (278, 435, 452, "r341-tr-q8"),    # سینماب
    (278, 476, 493, "r341-tr-q9"),    # صداب / رسش
    (278, 576, 593, "r341-tr-q11"),   # بیر ون
    (278, 660, 677, "r341-tr-q13"),   # تمیر / مهمه
    (278, 702, 719, "r341-tr-q14"),   # تنهاب
    (278, 765, 782, "r341-tr-q16"),   # !!!! + ترجمه
    (279, 40, 57, "r341-tr-q17"),     # تنهاب / یم شوید
    (279, 82, 99, "r341-tr-q18"),     # همکالیس / در خواست
    (279, 138, 155, "r341-tr-q19"),   # واقعأ / لباسهاب
    (279, 195, 213, "r341-tr-q20"),   # پسی / خییل / میر سید
]

for pno, y0, y1, name in STRIPS:
    page = doc[pno]
    w = page.rect.width
    pix = page.get_pixmap(matrix=fitz.Matrix(2000 / 72.0, 2000 / 72.0), clip=fitz.Rect(0.16 * w, y0, 0.99 * w, y1))
    out = f"/tmp/{name}.png"
    pix.save(out)
    print(out, pix.width, "x", pix.height)
