for pno, needle, name, pad_x, occ in ZOOMS:
    page = doc[pno - 1]
    def norm(s):
        return s.replace("\u200c", "").replace(" ", "").replace("\n", "")
    hits = [w for w in page.get_text("words") if needle.replace(" ", "") in norm(w[4])]
    if not hits:
        print(f"!! p{pno} '{needle}' NOT FOUND")
        continue
    w = hits[0] if occ == 1 else hits[occ - 1]
    r = fitz.Rect(w[0] - pad_x, w[1] - 20, w[2] + pad_x, w[3] + 22) & page.rect
    pix = page.get_pixmap(dpi=3000, clip=r)
    pix.save(str(OUT / f"{name}.png"))
    print(f"{name}: p{pno} '{needle}' -> {pix.width}x{pix.height}")
