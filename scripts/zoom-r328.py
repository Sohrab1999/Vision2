import fitz

PDF = "/home/z/my-project/upload/جزوه جامع دهم .pdf"
doc = fitz.open(PDF)

def clip(pno, dpi, name, x0, y0, x1, y1):
    page = doc[pno - 1]
    z = dpi / 72.0
    r = fitz.Rect(x0, y0, x1, y1)
    pix = page.get_pixmap(matrix=fitz.Matrix(z, z), clip=r)
    out = f"/tmp/r328-z-{name}.png"
    pix.save(out)
    print(f"{out}  {pix.width}x{pix.height}")

