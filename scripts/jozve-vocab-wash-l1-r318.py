FA = re.compile(r"[\u0600-\u06FF]")

def norm_tok(w):
    w = w.replace("\u200c", "").replace("ی", "ی").replace("ک", "ک")
    return w

def fold(t):
    t = t.replace("ال", "لا").replace("ی", "ی").replace("ک", "ک")
    return t

def sim(a, b):
    import difflib
    return difflib.SequenceMatcher(None, a, b).ratio()

def block_list(doc):
    """بلوک‌های ترجمهٔ ص۱۸۱-۱۸۴ — بر پایهٔ پارسرِ r318 (y<555 در ص۱۸۴)."""
    blocks = []
    cur = None
    for pno in PAGES:
        page = doc[pno - 1]
        d = page.get_text("dict")
        ycap = GRID_TOP if pno == 184 else 10**9
        items = []
        for blk in d.get("blocks", []):
            for ln in blk.get("lines", []):
                txt = "".join(sp["text"] for sp in ln.get("spans", [])).strip()
                if not txt:
                    continue
                y = ln["bbox"][1]
                if y >= ycap:
                    continue
                items.append((y, txt))
        items.sort()
        for y, txt in items:
            if re.fullmatch(r"[-ـ—\s]+", txt):
                continue
            if re.search(r"جزوه|جام|Vision|تألیف|گردآوری|پایه دو", txt) and len(txt) < 60:
                continue
            m = re.search(r"ترجمه تست\s*\(?([abcd])\)?\s*-\s*(\d{1,3})\b", txt)
            if m:
                if cur:
                    blocks.append(cur)
                cur = {"n": int(m.group(2)), "key": m.group(1), "frags": [txt[: m.start()].strip()]}
                continue
            if re.fullmatch(r"(\d{1,3})\s*[-–]?\s*\(?", txt.strip()):
                if cur:
                    blocks.append(cur)
                cur = {"n": int(re.search(r"(\d{1,3})", txt).group(1)), "key": None, "frags": []}
                continue
            if re.fullmatch(r"\(?([abcd])\)?", txt.strip()) and cur is not None and cur["key"] is None:
                cur["key"] = re.fullmatch(r"\(?([abcd])\)?", txt.strip()).group(1)
                continue
            if cur is not None:
                clean = re.sub(r"ترجمه تست", "", txt).strip()
                if clean and not re.fullmatch(r"[:\"'\s،؛\.]+", clean):
                    cur["frags"].append(clean)
    if cur:
        blocks.append(cur)
    # چاپِ جزوه شمارهٔ ۷۴ را دو بار چاپ کرده (بلوکِ دومِ «۷۴» = Q75 واقعی — زیر فشار بودن)
    # ریمپِ تکراری‌ها: nِ دیده‌شده → n+1 (رسیدِ r308: «the booklet printed number 228 twice»)
    seen = {}
    for b in blocks:
        n = b["n"]
        if n in seen:
            fixed = n + 1
            if fixed in seen:
                print(f"[blocks] FATAL — duplicate #{n} and #{fixed} both exist")
                sys.exit(1)
            b["n"] = fixed
            b["renumberedFrom"] = n
        seen[b["n"]] = True
    # حذفِ شبه‌بلوک‌های شمارهٔ صفحه (۱۸۱-۱۸۳)
    return [b for b in blocks if b["frags"] or b["key"]]

def grid_key(doc):
    """گریدِ ۱۰×۱۰ِ انتهای ص۱۸۴ — جفت‌های (عدد، حرف)."""
    page = doc[183]
    words = [w for w in page.get_text("words") if w[1] > GRID_TOP and w[1] < 800]
    ws = sorted(words, key=lambda w: (round(w[1] / 12), w[0]))
    grid = {}
    for w in ws:
        t = w[4]
        if re.fullmatch(r"\d{1,3}", t):
            grid.setdefault(round(w[1] / 12), []).append((w[0], "N", int(t)))
        elif re.fullmatch(r"[abcd]", t):
            grid.setdefault(round(w[1] / 12), []).append((w[0], "L", t))
    out = {}
    for _, seq in grid.items():
        i = 0
        while i + 1 < len(seq):
            (_, k1, v1), (_, k2, v2) = seq[i], seq[i + 1]
            if k1 == "N" and k2 == "L":
                out[v1] = v2
                i += 2
            else:
                i += 1
    return out

def fitz_tokens(doc, blocks):
    toks = {}
    for b in blocks:
        toks[b["n"]] = [w for f in b["frags"] for w in f.split()]
    return toks

