def norm(s):
    s = re.sub(r"[\u200c\u0640]", "", s)
    s = s.replace("ی", "ی").replace("ک", "ک").replace("ۀ", "ه").replace("أ", "ا").replace("آ", "ا")
    s = re.sub(r"\s+", " ", s).strip()
    return s

diffs = []
for n in sorted(TR):
    c = norm(cur.get(n, ""))
    t = norm(TR[n])
    if c != t:
        sm = difflib.SequenceMatcher(None, c, t)
        r = sm.ratio()
        diffs.append((n, r, c, t))
print("diff count:", len(diffs))
for n, r, c, t in diffs:
    print(f"\n--- Q{n} (sim={r:.2f})")
    print("  JSON:", c[:150])
    print("  PRNT:", t[:150])
