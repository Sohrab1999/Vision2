    page = doc[pno]
    w = page.rect.width
    pix = page.get_pixmap(matrix=fitz.Matrix(3000 / 72.0, 3000 / 72.0), clip=fitz.Rect(0.12 * w, y0, 0.995 * w, y1))
    out = f"/tmp/{name}.png"
    pix.save(out)
    print(out, pix.width, "x", pix.height)
