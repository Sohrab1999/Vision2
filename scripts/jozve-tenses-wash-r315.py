def md5(path):
    return hashlib.md5(open(path, "rb").read()).hexdigest()


def parse_key_pages():
    """کلیدِ حرفیِ هر ۳۰ آیتم از لایهٔ fitz + اثباتِ نشانگرِ «ترجمه» در بلوکِ هر آیتم."""
    doc = fitz.open(PDF)
    text = ""
    for p in KEY_PAGES:
        text += doc[p - 1].get_text() + "\n"
    starts = [(m.start(), int(m.group(1))) for m in ANCHOR.finditer(text)]
    seen = {}
    for i, (pos, num) in enumerate(starts):
        end = starts[i + 1][0] if i + 1 < len(starts) else text.find("بخش دوم")
        block = text[pos:end]
        if num in seen:
            sys.exit(f"FATAL: duplicate item {num}")
        km = KEY_FITZ.search(block)
        if not km:
            sys.exit(f"FATAL: no key letter in item {num} block")
        if "ترجم" not in block:
            sys.exit(f"FATAL: no printed-translation marker in item {num} block")
        seen[num] = km.group(1)
    expected = sorted(TRANSCRIPT.keys())
    if sorted(seen.keys()) != expected:
        sys.exit(f"FATAL: items mismatch {sorted(seen.keys())} != {expected}")
    return seen


