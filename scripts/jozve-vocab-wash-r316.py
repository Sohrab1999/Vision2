FA = re.compile(r"[\u0600-\u06FF]")

def norm_tok(s):
    s = s.strip().translate(str.maketrans("۰۱۲۳۴۵۶۷۸۹", "0123456789"))
    s = re.sub(r"[\u064B-\u065F\u0670\u0640\u200c]", "", s)
    return (s.replace("ي", "ی").replace("ك", "ک").replace("أ", "ا").replace("آ", "ا")
             .replace("ئ", "ی").replace("ء", ""))

def fold(s):
    # کلاس‌های اغتشاشِ شناخته‌شدهٔ ToUnicode برای تطبیقِ فازی
    return (s.replace("ی", "ت").replace("ن", "ت").replace("ل", "ا").replace("ر", "ی")
             .replace("و", "ی").replace("ه", "ر").replace("ب", "پ").replace("ط", "ص"))

def sim(a, b):
    import difflib
    return difflib.SequenceMatcher(None, a, b).ratio()

def fitz_tokens(doc):
    """توکن‌های هر آیتم از لایهٔ fitz (مرتبِ y سپس RTL) — برای کراس‌چک."""
    LIMIT218 = 316.0
    blocks = []
    for pno in PAGES:
        page = doc[pno - 1]
        dd = page.get_text("dict")
        dashes, bottom = [], None
        for blk in dd["blocks"]:
            for ln in blk.get("lines", []):
                txt = "".join(sp["text"] for sp in ln["spans"]).strip()
                y = min(sp["bbox"][1] for sp in ln["spans"])
                if re.match(r"^-{10,}$", txt):
                    dashes.append(y)
                if pno == 218 and y > LIMIT218:
                    bottom = y if bottom is None else min(bottom, y)
        dashes.sort()
        tops = [18.0] + [x + 3 for x in dashes]
        bots = [x - 2 for x in dashes] + ([bottom - 4] if bottom else [815.0])
        for y0, y1 in zip(tops, bots):
            if y1 - y0 > 14:
                blocks.append((pno, y0, y1))

    def i2b(it):
        if it <= 33:
            return it
        if it in (34, 35):
            return 34
        if 36 <= it <= 87:
            return it - 1
        return it

    out = {}
    for it in range(1, 101):
        bi = i2b(it)
        pno, y0, y1 = blocks[bi - 1]
        page = doc[pno - 1]
        W = page.rect.width
        words = page.get_text("words", clip=fitz.Rect(0, y0 - 2, W, y1 + 2))
        lines = {}
        for x0, yy0, x1, yy1, wt, *_ in words:
            lines.setdefault(round(yy0), []).append((x0, wt))
        toks = []
        for key in sorted(lines):
            row = sorted(lines[key], key=lambda t: -t[0])
            toks.extend(w for _, w in row)
        out[it] = toks
    return out

def grid_key(doc):
    """داوریِ کلید از هدرهای سرصفحه‌ای هر آیتم: (num, letter) در لبهٔ راستِ بلوکِ خودش"""
    LIMIT218 = 316.0
    blocks = []
    for pno in PAGES:
        page = doc[pno - 1]
        dd = page.get_text("dict")
        dashes, bottom = [], None
        for blk in dd["blocks"]:
            for ln in blk.get("lines", []):
                txt = "".join(sp["text"] for sp in ln["spans"]).strip()
                y = min(sp["bbox"][1] for sp in ln["spans"])
                if re.match(r"^-{10,}$", txt):
                    dashes.append(y)
                if pno == 218 and y > LIMIT218:
                    bottom = y if bottom is None else min(bottom, y)
        dashes.sort()
        tops = [18.0] + [x + 3 for x in dashes]
        bots = [x - 2 for x in dashes] + ([bottom - 4] if bottom else [815.0])
        for y0, y1 in zip(tops, bots):
            if y1 - y0 > 14:
                blocks.append((pno, y0, y1))

    def i2b(it):
        if it <= 33:
            return it
        if it in (34, 35):
            return 34
        if 36 <= it <= 88:
            return it - 1
        return it

    W = doc[214].rect.width
    fa2en = str.maketrans("۰۱۲۳۴۵۶۷۸۹", "0123456789")
    LET = re.compile(r"^\(?([abcd])\)?[,.;:]?$", re.I)
    NUMW = re.compile(r"^\(?-?([0-9]{1,3})\)?-?,?$")
    out = {}
    for it in range(1, 101):
        pno, y0, y1 = blocks[i2b(it) - 1]
        page = doc[pno - 1]
        words = page.get_text("words", clip=fitz.Rect(0, y0 - 2, W, y1 + 2))
        right = []
        for x0, yy0, x1, yy1, wt, *_ in words:
            if x0 < W * 0.70:
                continue
            t = wt.strip().translate(fa2en)
            m = LET.match(t)
            if m:
                right.append((yy0, "L", m.group(1).lower()))
                continue
            m = NUMW.match(t)
            if m and 1 <= int(m.group(1)) <= 100:
                right.append((yy0, "N", int(m.group(1))))
        right.sort()
        pairs = []
        for a in range(len(right)):
            for b in range(a + 1, len(right)):
                ya, ta, va = right[a]
                yb, tb, vb = right[b]
                if abs(ya - yb) < 2.5 and ta != tb:
                    num = va if ta == "N" else vb
                    let = va if ta == "L" else vb
                    if 1 <= num <= 100:
                        pairs.append((num, let))
        pick = [p for p in pairs if p[0] == it]
        out[it] = pick[0][1] if pick else None
    return out

