FA = re.compile(r"[\u0600-\u06FF]")

def norm_tok(s):
    s = s.strip().translate(str.maketrans("۰۱۲۳۴۵۶۷۸۹", "0123456789"))
    s = re.sub(r"[\u064B-\u065F\u0670\u0640\u200c]", "", s)
    return (s.replace("ي", "ی").replace("ك", "ک").replace("أ", "ا").replace("آ", "ا")
             .replace("ئ", "ی").replace("ء", ""))

def fold(s):
    return (s.replace("ی", "ت").replace("ن", "ت").replace("ل", "ا").replace("ر", "ی")
             .replace("و", "ی").replace("ه", "ر").replace("ب", "پ").replace("ط", "ص"))

def sim(a, b):
    import difflib
    return difflib.SequenceMatcher(None, a, b).ratio()

def block_list(doc):
    blocks = []
    for pno in PAGES:
        page = doc[pno - 1]
        dd = page.get_text("dict")
        dashes, bottom = [], None
        for blk in dd["blocks"]:
            for ln in blk.get("lines", []):
                txt = "".join(sp["text"] for sp in ln["spans"]).strip()
                y = min(sp["bbox"][1] for sp in ln["spans"])
                if re.match(r"^-{6,}$", txt.replace(" ", "")):
                    dashes.append(y)
                if pno == 202 and y > LIMIT202:
                    bottom = y if bottom is None else min(bottom, y)
        dashes = sorted(set(round(d) for d in dashes))
        if pno == 202:
            dashes = [d for d in dashes if d < LIMIT202]
        tops = [HDR_TOP] + [x + 3 for x in dashes]
        bots = [x - 2 for x in dashes] + ([bottom - 4] if bottom else [830.0])
        for y0, y1 in zip(tops, bots):
            if y1 - y0 > 14:
                blocks.append((pno, y0, y1))
    return blocks

def fitz_tokens(doc, blocks):
    out = {}
    for it in range(1, 101):
        pno, y0, y1 = blocks[it - 1]
        page = doc[pno - 1]
        W = page.rect.width
        words = page.get_text("words", clip=fitz.Rect(0, max(0, y0 - 2), W, min(y1 + 2, page.rect.height)))
        lines = {}
        for x0, yy0, x1, yy1, wt, *_ in words:
            lines.setdefault(round(yy0), []).append((x0, wt))
        toks = []
        for key in sorted(lines):
            row = sorted(lines[key], key=lambda t: -t[0])
            toks.extend(w for _, w in row)
        out[it] = toks
    return out

def header_key(doc, blocks):
    fa2en = str.maketrans("۰۱۲۳۴۵۶۷۸۹", "0123456789")
    LET = re.compile(r"^\(?([abcd])\)?[,.;:]?$", re.I)
    NUMW = re.compile(r"^\(?-?([0-9]{1,3})\)?-?,?$")
    out = {}
    for bi, (pno, y0, y1) in enumerate(blocks, 1):
        page = doc[pno - 1]
        W = page.rect.width
        words = page.get_text("words", clip=fitz.Rect(0, max(0, y0 - 2), W, min(y1 + 2, page.rect.height)))
        right = []
        for x0, yy0, x1, yy1, wt, *_ in words:
            if x0 < W * 0.70:
                continue
            t = wt.strip().translate(fa2en)
            m = LET.match(t)
            if m:
                right.append((yy0, "L", m.group(1).lower()))
                continue
            m = NUMW.match(t)
            if m and 1 <= int(m.group(1)) <= 100:
                right.append((yy0, "N", int(m.group(1))))
        right.sort()
        pairs = []
        for a in range(len(right)):
            for b in range(a + 1, len(right)):
                ya, ta, va = right[a]
                yb, tb, vb = right[b]
                if abs(ya - yb) < 2.5 and ta != tb:
                    num = va if ta == "N" else vb
                    let = va if ta == "L" else vb
                    if 1 <= num <= 100:
                        pairs.append((num, let))
        pick = [p for p in pairs if p[0] == bi]
        if pick:
            out[bi] = pick[0][1]
    return out

def grid_key(doc):
    page = doc[201]
    W = page.rect.width
    fa2en = str.maketrans("۰۱۲۳۴۵۶۷۸۹", "0123456789")
    cells = []
    for x0, yy0, x1, yy1, wt, *_ in page.get_text("words", clip=fitz.Rect(0, 210, W, 430)):
        t = wt.strip().translate(fa2en)
        m = re.match(r"^\(?([abcd])[.,]?$", t, re.I)
        if m:
            cells.append((yy0, x0, "L", m.group(1).lower()))
            continue
        m = re.match(r"^\(?(\d{1,3})\)?,?$", t)
        if m:
            n = int(m.group(1))
            if 1 <= n <= 100:
                cells.append((yy0, x0, "N", n))
    cells.sort(key=lambda c: (c[0], c[1]))
    rows = []
    for y, x, kind, val in cells:
        if rows and y - rows[-1]["y"] < 3:
            rows[-1]["cells"].append((x, kind, val))
            rows[-1]["y"] = max(rows[-1]["y"], y)
        else:
            rows.append({"y": y, "cells": [(x, kind, val)]})
    grid = {}
    for r in rows:
        seq = sorted(r["cells"], key=lambda c: -c[0])
        i = 0
        while i + 1 < len(seq):
            (_, k1, v1), (_, k2, v2) = seq[i], seq[i + 1]
            if k1 == "L" and k2 == "N":
                grid[v2] = v1
                i += 2
            else:
                i += 1
    return grid

