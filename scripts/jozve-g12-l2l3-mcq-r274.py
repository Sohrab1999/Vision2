def fix_fa(t):
    t = t.replace("ي", "ی").replace("ك", "ک").replace("‌ ", "‌")
    for a, b in WORD_FIXES.items():
        t = re.sub(rf"(?<![آ-ی]){re.escape(a)}(?![آ-ی])", b, t)
    t = re.sub(r"(?<![آ-ی])یم(?=\s)", "می", t)   # «تبدیل یم شود» → «تبدیل می شود»
    t = re.sub(r"(?<![آ-ی])ین(?=\s)", "می", t)   # «ننویسد»-خانواده
    # فعل‌های پرتکرار با فاصله → نیم‌فاصله («می شود» → «می‌شود»)
    MI_VERBS = (
        "شوم|شوی|شود|شویم|شوید|شوند|کنم|کنی|کند|کنیم|کنید|کنند|دهم|دهی|دهد|دهیم|دهید|دهند|"
        "دارم|داری|دارد|داریم|دارید|دارند|توانم|توانی|تواند|توانیم|توانید|توانند|"
        "آید|آورم|آورد|آورند|کردم|کرد|کردند|رسد|رسند|گردد|باشد|باشند|بشود|گیرد|گیرند|"
        "خورد|خورند|کشند|بخشد|سازد|سازند|گذارید|بگذارید|گویم|گوید|گویند|بینم|بیند|بینند"
    )
    t = re.sub(rf"(?<![آ-ی])می ({MI_VERBS})(?![آ-ی])", r"می‌\1", t)
    # «نیم X» منفی‌سازِ شکسته → «نمی‌X» (وگرنه «نیم ساعت» سالم می‌ماند)
    t = re.sub(rf"(?<![آ-ی])نیم ({MI_VERBS})(?![آ-ی])", r"نمی‌\1", t)
    return re.sub(r"\s{2,}", " ", t).strip()


def extract(spec):
    print(f"== درس {spec['lesson']} (pages {spec['sourcePages']}, {spec['chapter']}) ==")
    qs = parse_questions(spec["pages"])
    print(f"  parsed questions: {len(qs)} (expect 100)")
    g12 = json.load(open(G12))
    ch = next(c for c in g12["chapters"] if c["id"] == spec["chapter"])
    grid = load_grid(ch["sections"])
    trans, tlet = load_translations(ch["sections"])
    print(f"  grid keys: {len(grid)}, quick translations: {len(trans)}")
    return qs, grid, trans, tlet


def main():
    dry = "--dry" in sys.argv
    verbose_tr = "--dump-tr" in sys.argv
    all_lessons = []
    global_problems = []

    for spec in LESSONS:
        qs, grid, trans, tlet = extract(spec)
        problems, overrides = [], []
        out = []
        fa_pat = re.compile(r"[\u0600-\u06FF]")
        en_pat = re.compile(r"[A-Za-z]")
        divergences = []
        for n in range(1, 101):
            q = qs.get(n)
            if not q:
                problems.append(f"L{spec['lesson']} Q{n}: missing")
                continue
            stem = norm_stem(" ".join(q["stem"]))
            opts = [re.sub(r"\s{2,}", " ", o).strip() for o in q["opts"]]
            if len(opts) != 4:
                problems.append(f"L{spec['lesson']} Q{n}: {len(opts)} options {opts}")
                continue
            if len(set(opts)) != 4:
                problems.append(f"L{spec['lesson']} Q{n}: duplicate options {opts}")
            let = grid.get(n)
            if let is None:
                problems.append(f"L{spec['lesson']} Q{n}: no key")
                continue
            if fa_pat.search(stem) or any(fa_pat.search(o) for o in opts):
                problems.append(f"L{spec['lesson']} Q{n}: Persian leaked into English")
            if not re.search(r"-{5,}", stem):
                problems.append(f"L{spec['lesson']} Q{n}: no blank in stem: {stem[:60]}")
            restored = False
            restore_map = RESTORE_L2 if spec["lesson"] == 2 else (RESTORE_L3 if spec["lesson"] == 3 else {})
            if n in restore_map:
                tr, restored = restore_map[n], True
            else:
                tr = fix_fa(trans.get(n, "")) if n in trans else ""
            if tr and tlet.get(n) != let and not restored:
                divergences.append((n, tlet.get(n), let, opts, tr))
            ans = "abcd".index(let)
            if tr:
                tr_clean = tr
                for ok in TR_LATIN_OK:
                    tr_clean = tr_clean.replace(ok, "")
                tr_clean = re.sub(r"\b(Vision|Three)\b", "", tr_clean)
                if re.search(r"[A-Za-z]{3,}", tr_clean):
                    problems.append(f"L{spec['lesson']} Q{n}: Latin in translation: {tr_clean[:60]}")
            out.append({
                "id": f"g12-l{spec['lesson']}-{n}", "n": n, "category": "vocab",
                "question": stem, "options": opts, "answer": ans,
                **({"translation": tr} if tr else {}),
            })
        restorations = [n for n in range(1, 101) if n in (RESTORE_L2 if spec["lesson"] == 2 else (RESTORE_L3 if spec["lesson"] == 3 else {}))]

        if divergences:
            print(f"  — {len(divergences)} واگراییِ ترجمه/شبکه (برای داوری):")
            for n, tl, gl, opts, tr in divergences:
                print(f"    Q{n}: grid={gl} trans-letter={tl}")
                print(f"      stem: {out[n-1]['question'][:90]}")
                print(f"      opts: {opts}")
                print(f"      tr:   {tr[:100]}")
        missing_tr = [q["n"] for q in out if not q.get("translation")]
        if missing_tr:
            print(f"  ترجمهٔ غایب (صداقتِ رسید): {missing_tr}")
        if verbose_tr:
            for q in out:
                if q.get("translation"):
                    print(f"    TR Q{q['n']}: {q['translation']}")
        all_lessons.append({
            "spec": spec, "out": out, "overrides": overrides, "problems": problems,
            "restorations": restorations,
        })
        global_problems.extend(problems)

    if global_problems:
        print("\nPROBLEMS:")
        for p in global_problems[:40]:
            print("  -", p)
        sys.exit(1)

    if dry:
        print("\n[dry] بدون نوشتن — فقط گزارش. با حذف --dry بانک نوشته می‌شود.")
        return

    bank = json.load(open(BANK))
    have = {l["lesson"] for l in bank["lessons"]}
    for item in all_lessons:
        spec, out, overrides = item["spec"], item["out"], item["overrides"]
        if spec["lesson"] in have:
            print(f"  skip: درس {spec['lesson']} از قبل در بانک است")
            continue
        lesson = {
            "lesson": spec["lesson"],
            "title": spec["title"],
            "count": len(out),
            **({"answerArbitration": overrides} if overrides else {}),
            **({"translationRestorations": {
                "count": len(item["restorations"]),
                "note": "لایهٔ متنی PDF سرصفحه‌های ترجمه را وسط خط/جابه‌جا برده بود؛ هر ترجمه از قطعاتِ خودِ جزوه بازچینی شد — هیچ محتوایی جز اصلاحات واژگانیِ ثبت‌شده اضافه/حذف نشد.",
                "questions": item["restorations"],
            }} if item["restorations"] else {}),
            "source": {
                "file": "جزوه_جامع_پایه_دوازدهم_با_امتحانات_نهایی_.pdf",
                "questionPages": spec["sourcePages"],
                "keyGrid": spec["keyNote"],
            },
            "questions": out,
        }
        bank["lessons"].append(lesson)
        if overrides:
            print(f"  overrides L{spec['lesson']}: {[(o['q'], o['letter']) for o in overrides]}")
    bank["lessons"].sort(key=lambda l: l["lesson"])
    with open(BANK, "w") as f:
        json.dump(bank, f, ensure_ascii=False)
    print(f"\nOK → {BANK} ({os.path.getsize(BANK)//1024}KB, lessons={[l['lesson'] for l in bank['lessons']]})")


if __name__ == "__main__":
    main()
