JUNK_RE = [re.compile(p) for p in JUNK_SUB]
BRACKET_ONLY = re.compile(r"^[\)\(\[\]\"\u201c\u201d\s:؛،]*$")
FA_CHAR = re.compile(r"[\u0600-\u06FF]")

BLANK_FIX = re.compile(r"-+(?:\s+-+)+")
BLANK_RUN = re.compile(r"-{2,}")
BLANK = "-" * 15

OPT_SEG = re.compile(r"(?:^|\s)([a-d])\s*\.\s*")


def clean_page(lines):
    out = []
    for ln in lines:
        s = ln.strip()
        if not s or BRACKET_ONLY.match(s):
            continue
        if any(rx.search(s) for rx in JUNK_RE):
            continue
        out.append(s)
    return out


def split_option_line(s, start=0):
    """قطعه‌شکن گزینه‌های تک‌خطی: «a. x   b. y   c. z   d. w» → [x, y, z, w]
    start = اندیس حرفِ انتظاری بعدی (برای ادامهٔ دوتکه: خط دوم با c شروع می‌شود)"""
    marks = list(OPT_SEG.finditer(s))
    letters = [m.group(1) for m in marks]
    want = ["a", "b", "c", "d"][start: start + len(letters)]
    if not letters or letters != want:
        return None
    out = []
    for i, m in enumerate(marks):
        end = marks[i + 1].start() if i + 1 < len(marks) else len(s)
        out.append(re.sub(r"\s{2,}", " ", s[m.end():end]).strip())
    return out


def parse_questions(pages):
    doc = fitz.open(PDF)
    raw = []
    for p in pages:
        raw.extend(doc[p].get_text("text").splitlines())
    lines = clean_page(raw)

    qs, cur, expect = {}, None, 1
    for ln in lines:
        mq = re.match(r"^(\d{1,3})\.\s*(.*)$", ln)
        if mq and int(mq.group(1)) == expect:
            n = int(mq.group(1))
            if cur is not None and len(cur["opts"]) != 4:
                print(f"  warn: L{pages[0]} Q{cur['n']} incomplete ({len(cur['opts'])} opts) before Q{n}")
            cur = {"n": n, "stem": [mq.group(2)], "opts": []}
            qs[n] = cur
            expect = n + 1
            continue
        if cur is None:
            continue
        if len(cur["opts"]) < 4:
            segs = split_option_line(ln, start=len(cur["opts"])) if re.match(r"^[a-d]\s*\.", ln) else None
            if segs:
                cur["opts"].extend(segs)
                continue
            mo = re.match(r"^([a-d])\s*\.\s*(.*)$", ln)
            if mo:
                cur["opts"].append(mo.group(2).strip())
                continue
            if not FA_CHAR.search(ln):  # ادامهٔ ساقه/گزینه فقط انگلیسی
                if cur["opts"]:
                    cur["opts"][-1] += " " + ln
                else:
                    cur["stem"].append(ln)
    return qs


def norm_stem(s):
    s = BLANK_FIX.sub(f" {BLANK} ", s)
    s = BLANK_RUN.sub(BLANK, s)
    return re.sub(r"\s{2,}", " ", s).strip()


def load_grid(secs):
    """اولین سکشن با ≥۹۰ جفت یکتای 1..100 → شبکهٔ کلید"""
    for i, s in enumerate(secs):
        joined = " ".join(s["lines"])
        pairs = re.findall(r"(?<![A-Za-z\d])(\d{1,3})\s+([a-d])(?![A-Za-z])", joined)
        uniq = {}
        for num, let in pairs:
            uniq.setdefault(int(num), let)
        if len(uniq) >= 90 and min(uniq) <= 3 and max(uniq) >= 97:
            print(f"  grid: sec{i} ({len(uniq)} keys)")
            return uniq
    return {}


# کلاس پیش‌موند گسترده: لایهٔ متنی PDF سرصفحه‌ها را وسط خط می‌برد (بعد از نقطه/ویرگول/رقم)
TR_PAT = re.compile(
    r"^[\s\u0600-\u06FF(){}\[\]\"'«».,،؛:؟!0-9\u200c]*([a-d])[\s()\[\]]*-\s*(\d{1,3})\s*(.*)$"
)
# سرصفحهٔ توکار داخل خط ادامه (مثل «شکل ر (d) -20اگر برای...»)
EMB_TR = re.compile(r"[\(\[]?\s*([a-d])\s*\)?\s*-\s*(\d{1,3})(?!\d)")
# قطعات یتیم لایهٔ متنی: تک‌حرف‌های ی/ر یا حرکات تنها
ORPHAN = re.compile(r"^[\s\u200c\u064B-\u065Fری]*$")


def strip_tr_marker(s):
    s = s.strip()
    s = re.sub(r"^(?:ترجمه\s*تست\s*[:：]?|ترجمه\s*[:：]|[:：])\s*", "", s)
    return s.strip()


def load_translations(secs):
    """سکشن ۰ → ترجمهٔ سریع؛ الگوی «(X)-Nمتن» (c14/c15) یا «)X( -Nترجمه تست :متن» (c13)
    + شکستِ سرصفحهٔ توکار (لایهٔ متنی c15 سرصفحه‌ها را وسط خط می‌برد)
    + فیلترِ قطعات یتیم تک‌حرفی (ی/ر/حرکات)"""
    trans, tlet = {}, {}
    pending = None
    for ln in secs[0]["lines"]:
        t = ln.strip()
        if not t or ORPHAN.match(t):
            continue  # خط خالی یا قطعهٔ یتیم — pending زنده می‌ماند
        m = TR_PAT.match(t)
        if m:
            pending = int(m.group(2))
            if pending not in trans:  # اولین occurrence برنده
                tlet[pending] = m.group(1)
                trans[pending] = strip_tr_marker(m.group(3))
            continue
        if pending is None:
            continue
        m2 = EMB_TR.search(t)
        nxt = re.match(r"^-{0,2}\s*\d{1,3}\s*(گزینه|ترجمه)", t)
        if m2 and int(m2.group(2)) != pending:
            # پیش‌دسته → ترجمهٔ جاری؛ باقیمانده → ترجمهٔ جدید (سرصفحهٔ توکار)
            head = t[: m2.start()].strip()
            if head:
                trans[pending] += " " + head
            new_n = int(m2.group(2))
            if new_n not in trans:
                tlet[new_n] = m2.group(1)
                trans[new_n] = strip_tr_marker(t[m2.end():])
                pending = new_n
        elif nxt:
            pending = None
        else:
            trans[pending] += " " + t
    return trans, tlet


