# برش‌های ۹۰۰-۱۸۰۰dpi برای سربرگ‌ها و ریز-داوری‌های ترجمه
import fitz
from pathlib import Path

PDF = "/home/z/my-project/upload/جزوه جامع دهم .pdf"
OUT = Path("/tmp/qa-r347")
OUT.mkdir(exist_ok=True)
doc = fitz.open(PDF)

# (نام، شماره صفحه ۱-مبنا، rect نسبی (x0,y0,x1,y1) در بازه ۰-۱، dpi)
CROPS = [
    ("A-p161-header",      161, (0.05, 0.075, 0.98, 0.155), 900),
    ("B-p163-header",      163, (0.05, 0.075, 0.98, 0.165), 900),
    ("C-p290-header",      290, (0.05, 0.075, 0.98, 0.170), 900),
    ("D-p291-header",      291, (0.05, 0.075, 0.98, 0.175), 900),
    ("E-p290-s3key",       290, (0.05, 0.42, 0.98, 0.585), 1200),
    ("F-p158-answerkey",   158, (0.05, 0.72, 0.98, 0.99), 1200),
    ("G-p290-s6key",       290, (0.05, 0.845, 0.98, 0.995), 1200),
    ("H-p291-q3",          291, (0.05, 0.185, 0.98, 0.245), 1800),
    ("H-p291-q4",          291, (0.05, 0.245, 0.98, 0.310), 1800),
    ("H-p291-q9",          291, (0.05, 0.545, 0.98, 0.660), 1800),
    ("H-p291-q11",         291, (0.05, 0.700, 0.98, 0.775), 1800),
    ("H-p291-q12",         291, (0.05, 0.775, 0.98, 0.845), 1800),
    ("I-p292-q16",         292, (0.05, 0.075, 0.98, 0.145), 1800),
    ("I-p292-q18",         292, (0.05, 0.215, 0.98, 0.290), 1800),
    ("J-p158-drill",       158, (0.05, 0.575, 0.98, 0.755), 1200),
    ("K-p163-q8-divider",  163, (0.05, 0.345, 0.98, 0.415), 1200),
    ("L-p162-note",        162, (0.05, 0.60, 0.98, 0.70), 900),
]

for name, pno, rel, dpi in CROPS:
    page = doc[pno - 1]
    r = page.rect
    clip = fitz.Rect(r.width * rel[0], r.height * rel[1], r.width * rel[2], r.height * rel[3])
    pix = page.get_pixmap(matrix=fitz.Matrix(dpi / 72, dpi / 72), clip=clip)
    path = OUT / f"{name}.png"
    pix.save(path)
    print(f"{name}: {pix.width}x{pix.height} -> {path}")
